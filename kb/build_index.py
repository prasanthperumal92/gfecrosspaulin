#!/usr/bin/env python3
"""Rebuild kb/INDEX.md and kb/index.json from the front matter of kb/*.md.

Run after adding or editing a KB page: python3 kb/build_index.py
Only files in kb/ are indexed (TODO.html is deliberately excluded).
"""
import json, pathlib, re

KB = pathlib.Path(__file__).resolve().parent
SKIP = {"INDEX.md"}


def parse(path):
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit(f"{path.name}: missing front matter")
    meta = {}
    for line in m[1].splitlines():
        k, v = line.split(":", 1)
        v = v.strip()
        meta[k.strip()] = [t.strip() for t in v.strip("[]").split(",")] if v.startswith("[") else v
    body = text[m.end():]
    meta["file"] = path.name
    meta["headings"] = re.findall(r"^#{2,3} (.+)$", body, re.M)
    meta["sources"] = sorted(set(re.findall(r"\b[SPG]\d+\b", body)), key=lambda s: (s[0], int(s[1:])))
    meta["summary"] = next((l.strip() for l in body.splitlines()
                            if l.strip() and not l.startswith(("#", "|", "-", "`", "```"))), "")
    return meta


pages = sorted((parse(p) for p in KB.glob("*.md") if p.name not in SKIP), key=lambda m: m["id"])

lines = ["# Tarpaulin Knowledge Base: Index", "",
         "Knowledge base for the Crosspaulin™ (KB-01 to KB-13) and Purity PVC (KB-14 to KB-17) export brochures (Grace Ferro Exports Pvt Ltd).",
         "Generated by `kb/build_index.py`; do not edit by hand. Machine-readable copy: `index.json`.", "",
         "## Pages", "", "| ID | Page | Sections | Sources |", "|---|---|---|---|"]
for p in pages:
    lines.append(f"| {p['id']} | [{p['title']}]({p['file']}) | {'; '.join(p['headings']) or '-'} | {', '.join(p['sources']) or '-'} |")

tags = {}
for p in pages:
    for t in p["tags"]:
        tags.setdefault(t.lower(), []).append(p)
lines += ["", "## Keyword index", ""]
for t in sorted(tags):
    lines.append(f"- **{t}**: " + ", ".join(f"[{p['id']}]({p['file']})" for p in tags[t]))

lines += ["", "## Quick answers", "",
          "| Question | Go to |", "|---|---|",
          "| Who is the exporter, and their contact details? | [KB-01](company.md) |",
          "| Who makes Crosspaulin? | [KB-02](manufacturer.md) |",
          "| What are the advantages, and are the claims sourced? | [KB-03](product.md) |",
          "| What are the specs per GSM? | [KB-04](specifications.md) |",
          "| Which standard applies? | [KB-05](standards.md) |",
          "| Lead time, payment, Incoterms, container loading? | [KB-06](export-terms.md) |",
          "| What is it used for? | [KB-07](applications.md) |",
          "| What sizes, and how many per pack? | [KB-08](sizes-and-packing.md) |",
          "| Colours, fonts, logo rules? | [KB-09](brand.md) |",
          "| Which photo shows what? | [KB-10](image-library.md) |",
          "| How do I rebuild the PDF or generate images? | [KB-11](brochure-build.md) |",
          "| What is still unknown? | [KB-12](open-questions.md) |",
          "| Where did a fact come from? | [KB-13](sources.md) |",
          "| Purity PVC: grades, sizes, what is known? | [KB-14](purity-product.md) |",
          "| Purity PVC: palette and images? | [KB-15](purity-brand.md) |",
          "| Purity PVC: export terms, internal prices? | [KB-16](purity-export-terms.md) |",
          "| Purity PVC: what is still unknown? | [KB-17](purity-open-questions.md) |", ""]
(KB / "INDEX.md").write_text("\n".join(lines))
(KB / "index.json").write_text(json.dumps(pages, indent=2, ensure_ascii=False) + "\n")
print(f"indexed {len(pages)} pages, {len(tags)} keywords")
